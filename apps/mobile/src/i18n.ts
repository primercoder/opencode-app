const dictionaries: Record<Language, Record<Key, string>> = { zh, en }

export function translate(language: Language, key: Key, vars?: Record<string, string | number>): string {
  const template = dictionaries[language][key] ?? zh[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/gu, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  )
}

export type TFunction = (key: Key, vars?: Record<string, string | number>) => string

export function useT(): TFunction {
  const language = usePreferences((state) => state.language)
  return useCallback<TFunction>((key, vars) => translate(language, key, vars), [language])
}

